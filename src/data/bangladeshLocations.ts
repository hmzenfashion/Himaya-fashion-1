/**
 * Checks if a given location qualifies for "Inside Dhaka" metro rate
 * Dhaka City Metropolitan thanas are Inside Dhaka.
 * Outer Dhaka (Savar, Dhamrai, Keraniganj, Dohar, Nawabganj) or other districts are Outside Dhaka.
 */
export function isDhakaMetro(division: string, district: string, thana: string): boolean {
  if (!division || !district) return false;
  
  const isDhakaDivision = division.toLowerCase().includes('dhaka');
  const isDhakaDistrict = district.toLowerCase().includes('dhaka');

  if (!isDhakaDivision || !isDhakaDistrict) {
    return false;
  }

  // Outer Dhaka upazilas are outside metro
  const lowerThana = thana.toLowerCase();
  const outerUpazilas = ['savar', 'dhamrai', 'keraniganj', 'dohar', 'nawabganj', 'সাভার', 'ধামরাই', 'কেরানীগঞ্জ', 'দোহার', 'নবাবগঞ্জ'];
  for (const outer of outerUpazilas) {
    if (lowerThana.includes(outer)) {
      return false;
    }
  }

  return true;
}
